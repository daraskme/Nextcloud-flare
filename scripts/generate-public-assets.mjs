import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";

const manifest = JSON.parse(
  await readFile(new URL("../packages/web/dist/.vite/manifest.json", import.meta.url), "utf8"),
);
assert.equal(manifest["public-share.html"]?.isEntry, true);
const visited = new Set();
const paths = new Set();
function visit(key) {
  if (visited.has(key)) return;
  visited.add(key);
  const chunk = manifest[key];
  assert.ok(chunk, `missing public chunk ${key}`);
  for (const path of [chunk.file, ...(chunk.css ?? []), ...(chunk.assets ?? [])]) {
    assert.match(path, /^public-assets\/[A-Za-z0-9_.-]+$/);
    paths.add(`/${path}`);
  }
  for (const dependency of [...(chunk.imports ?? []), ...(chunk.dynamicImports ?? [])])
    visit(dependency);
}
visit("public-share.html");
await writeFile(
  new URL("../packages/worker/src/assets/publicManifest.ts", import.meta.url),
  `// Generated by scripts/generate-public-assets.mjs from the public share Vite entry.\nexport const publicAssets = [\n${[
    ...paths,
  ]
    .sort()
    .map((path) => `  ${JSON.stringify(path)},`)
    .join("\n")}\n] as const;\n`,
);
console.log(`Public share entry manifest: ${paths.size} exact asset paths.`);
