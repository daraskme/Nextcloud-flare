import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../packages/web/dist/", import.meta.url);
const manifest = JSON.parse(await readFile(new URL(".vite/public-manifest.json", root), "utf8"));
const entry = manifest["public.html"];
assert.equal(entry?.isEntry, true);
assert.equal(Object.keys(manifest).length, 1, "public entry must be self-contained");
assert.equal((entry.imports ?? []).length + (entry.dynamicImports ?? []).length, 0);
const assets = [];
let html = await readFile(new URL("public.html", root), "utf8");
for (const file of [entry.file, ...(entry.css ?? [])]) {
  assert.match(file, /^public-assets\/public-share\.[A-Za-z0-9_-]+\.(js|css)$/);
  const bytes = await readFile(new URL(file, root));
  assert.ok(bytes.length > 0 && bytes.length <= 524288);
  const integrity = `sha384-${createHash("sha384").update(bytes).digest("base64")}`;
  assets.push({ path: `/${file}`, auth: "public", integrity, bytes: bytes.length });
  let hits = 0;
  html = html.replace(/<(script|link)\b[^>]*>/g, (tag) => {
    if (!tag.includes(`"/${file}"`)) return tag;
    hits++;
    return tag
      .replace(/\s+crossorigin(?:="[^"]*")?/, "")
      .replace(/>$/, ` integrity="${integrity}" crossorigin="anonymous">`);
  });
  assert.equal(hits, 1, `one integrity tag required: ${file}`);
}
assert.ok(
  assets.some((a) => a.path.endsWith(".js")) && assets.some((a) => a.path.endsWith(".css")),
);
assert.ok(!html.includes("private-assets") && !html.includes("/src/"));
await writeFile(new URL("public.html", root), html);
const page = Buffer.from(html);
const data = {
  page: {
    integrity: `sha384-${createHash("sha384").update(page).digest("base64")}`,
    bytes: page.length,
  },
  assets,
};
await writeFile(
  new URL("../packages/worker/src/assets/publicManifest.ts", import.meta.url),
  [
    "// Generated by scripts/generate-public-assets.mjs.",
    "export const publicManifest = {",
    "  page: {",
    `    integrity: ${JSON.stringify(data.page.integrity)},`,
    `    bytes: ${data.page.bytes},`,
    "  },",
    "  assets: [",
    ...assets.flatMap((asset) => [
      "    {",
      `      path: ${JSON.stringify(asset.path)},`,
      '      auth: "public",',
      `      integrity: ${JSON.stringify(asset.integrity)},`,
      `      bytes: ${asset.bytes},`,
      "    },",
    ]),
    "  ],",
    "} as const;",
    "",
  ].join("\n"),
);
console.log(`Public entry: ${assets.length} exact assets with SRI and verified module boundary.`);
